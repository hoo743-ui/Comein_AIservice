-- Comein · 일정의 중요도 — 겹쳤을 때 무엇을 물어야 하는지 알기 위해
--
-- 이 칸은 사실 이미 반쯤 있었다. AI 는 예전부터 `priority`(high/mid/low)를 뽑아 왔고
-- (`backend/app/schemas/items.py`), 화면도 그 값을 영수증까지 들고 왔다. 그런데
-- **`events` 에 앉을 자리가 없어서** 저장되지 않았다 — 뽑아 놓고 버리는 값이었다.
--
-- 왜 이제 필요한가 —
--   시간이 겹칠 때 사람이 알고 싶은 것은 "겹쳤다" 가 아니라 **"무엇을 포기해야 하나"** 다.
--   그 판단에는 두 일정이 각각 얼마나 중요한지가 있어야 한다. 없으면 화면이 할 수 있는
--   말은 "겹쳐요" 한 마디뿐이고, 그건 사람이 이미 아는 것이다.
--
-- 무엇을 하지 않는가 —
--   **자동으로 정리하지 않는다.** 낮은 것을 밀어내거나 옮기지 않는다. 중요도는 물음을
--   더 정확하게 만들 뿐, 결정을 대신하지 않는다(§0 — AI 는 조용히 돕고, 확정은 사람이 한다).
--
-- 적용: Supabase 대시보드 → SQL Editor 에 통째로 붙여넣고 Run

alter table public.events
  add column if not exists priority text
  check (priority is null or priority in ('high', 'mid', 'low'));

-- 비어 있는 것과 'mid' 는 다르다.
--   null  아무도 말하지 않았다 (대부분의 일정이 여기다)
--   mid   보통이라고 **말했다**
-- 기본값을 두지 않는 이유가 그것이다 — 말하지 않은 것을 말한 것으로 바꾸면, 겹쳤을 때
-- "둘 다 보통이니 아무거나" 라는 틀린 근거가 생긴다.

-- 겹침을 물을 때 그 날의 일정을 훑는다. 이미 events_start_idx 가 있어 따로 세우지 않는다.

comment on column public.events.priority is
  '중요도(high/mid/low). null = 말하지 않음. 겹쳤을 때 무엇을 물을지 정하는 데만 쓴다 — 자동으로 옮기거나 지우지 않는다.';
